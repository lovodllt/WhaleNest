"""Install this copy as a Linux user service; no WeChat recreation."""
from pathlib import Path
import subprocess
import sys

root=Path(__file__).resolve().parents[1]
unit=Path.home()/'.config/systemd/user/dafeiyu.service'
unit.parent.mkdir(parents=True,exist_ok=True)
text=f'''# Generated by Dafeiyu
[Unit]
Description=Dafeiyu local companion
After=network-online.target
[Service]
Type=simple
WorkingDirectory={root}
ExecStart="{root}/.venv/bin/python" "{root}/scripts/manage.py" supervise
Restart=on-failure
RestartSec=10
[Install]
WantedBy=default.target
'''
if unit.exists() and '# Generated by Dafeiyu' not in unit.read_text(encoding='utf-8'):raise SystemExit('已有同名服务，未覆盖')
unit.write_text(text,encoding='utf-8')
subprocess.run(['systemctl','--user','daemon-reload'],check=True)
subprocess.run(['systemctl','--user','enable','dafeiyu.service'],check=True)
print('已启用登录后自启。先用 stop.sh 停止手动实例，再运行 systemctl --user start dafeiyu.service')
